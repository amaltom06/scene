import test from 'node:test'
import assert from 'node:assert/strict'
import { randomBytes } from 'node:crypto'
import { spawn } from 'node:child_process'
import { createServer } from 'node:net'
import { createServer as createHttpServer } from 'node:http'
import { mkdtemp, rm } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import path from 'node:path'
import mongoose from 'mongoose'

const freePort = () => new Promise((resolve, reject) => {
  const probe = createServer().once('error', reject).listen(0, '127.0.0.1', () => { const port = probe.address().port; probe.close(() => resolve(port)) })
})

test('registration, profiles, discovery, privacy, capacity and chat authorization', async () => {
  const port = await freePort()
  const database = `scene_test_${randomBytes(6).toString('hex')}`
  const mongoUri = `mongodb://127.0.0.1:27017/${database}`
  const avatarDirectory = await mkdtemp(path.join(tmpdir(), 'scene-avatars-test-'))
  const base = `http://127.0.0.1:${port}`
  const mailbox = new Map()
  const emailServer = createHttpServer((request, response) => { const chunks = []; request.on('data', (chunk) => chunks.push(chunk)); request.on('end', () => { const message = JSON.parse(Buffer.concat(chunks).toString()); mailbox.set(message.to[0], message); response.writeHead(200, { 'Content-Type': 'application/json' }); response.end('{}') }) })
  await new Promise((resolve) => emailServer.listen(0, '127.0.0.1', resolve))
  const emailApiUrl = `http://127.0.0.1:${emailServer.address().port}/emails`
  const server = spawn(process.execPath, ['server/index.js'], { cwd: process.cwd(), env: { ...process.env, PORT: String(port), MONGODB_URI: mongoUri, AUTH_SECRET: randomBytes(48).toString('hex'), CORS_ORIGIN: base, NODE_ENV: 'test', RESEND_API_KEY: 'test-key', EMAIL_FROM: 'SCENE <test@example.test>', PUBLIC_APP_URL: base, RESEND_API_URL: emailApiUrl, AVATAR_UPLOAD_DIR: avatarDirectory }, stdio: ['ignore', 'pipe', 'pipe'] })
  let logs = ''; server.stdout.on('data', (chunk) => { logs += chunk }); server.stderr.on('data', (chunk) => { logs += chunk })
  const request = async (path, { method = 'GET', cookie, body } = {}) => {
    const response = await fetch(base + path, { method, headers: { ...(cookie ? { Cookie: cookie } : {}), ...(body ? { 'Content-Type': 'application/json' } : {}) }, body: body ? JSON.stringify(body) : undefined })
    return { status: response.status, cookie: response.headers.get('set-cookie')?.split(';')[0], data: response.status === 204 ? null : await response.json() }
  }
  try {
    let ready = false
    for (let attempt = 0; attempt < 80; attempt += 1) {
      try { const health = await request('/api/health'); if (health.data.database === 'connected') { ready = true; break } } catch { /* server still starting */ }
      await new Promise((resolve) => setTimeout(resolve, 100))
    }
    assert.ok(ready, `Test API did not connect to local MongoDB: ${logs}`)
    const register = async (username) => {
      const result = await request('/api/auth/register', { method: 'POST', body: { username, email: `${username.toLowerCase()}@example.test`, password: 'correct-horse-battery-staple' } })
      assert.equal(result.status, 201, JSON.stringify(result.data)); assert.equal(result.data.verificationSent, true); return result.cookie
    }
    const host = await register('TestHost')
    const guest = await register('TestGuest')
    const other = await register('TestOther')
    const verificationToken = mailbox.get('testhost@example.test').html.match(/\?verify=([A-Za-z0-9_-]+)/)?.[1]
    assert.ok(verificationToken)
    const verified = await request('/api/auth/verify', { method: 'POST', body: { token: verificationToken } })
    assert.equal(verified.status, 200)
    assert.equal((await request('/api/auth/me', { cookie: host })).data.user.emailVerified, true)
    const profile = await request('/api/users/me', { method: 'PATCH', cookie: host, body: { displayName: 'Test Host', city: 'Kochi', bio: 'Local music', interests: ['Music', 'Food'], privateAccount: false, shareAttendance: false } })
    assert.equal(profile.status, 200)
    assert.equal(profile.data.user.city, 'Kochi')
    const photo = Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+/lT8AAAAASUVORK5CYII=', 'base64')
    const deniedPhoto = await fetch(base + '/api/users/me/avatar', { method: 'POST', headers: { 'Content-Type': 'image/png' }, body: photo })
    assert.equal(deniedPhoto.status, 401)
    const invalidPhoto = await fetch(base + '/api/users/me/avatar', { method: 'POST', headers: { Cookie: host, 'Content-Type': 'image/jpeg' }, body: photo })
    assert.equal(invalidPhoto.status, 400)
    const uploadedPhoto = await fetch(base + '/api/users/me/avatar', { method: 'POST', headers: { Cookie: host, 'Content-Type': 'image/png' }, body: photo })
    assert.equal(uploadedPhoto.status, 200)
    const photoResult = await uploadedPhoto.json()
    assert.match(photoResult.user.avatar, /^\/api\/avatars\/[a-f0-9]{32}\.png$/)
    const servedPhoto = await fetch(base + photoResult.user.avatar)
    assert.equal(servedPhoto.status, 200)
    assert.deepEqual(Buffer.from(await servedPhoto.arrayBuffer()), photo)
    assert.equal((await request('/api/auth/me', { cookie: host })).data.user.avatar, photoResult.user.avatar)
    const start = new Date(Date.now() + 86400000)
    const end = new Date(start.getTime() + 7200000)
    const sceneBody = { title: 'Test Scene', description: 'An integration test meetup', category: 'Casual Hangouts', city: 'Kochi', area: 'Edappally', venue: 'Public cafe', capacity: 2, startsAt: start.toISOString(), endsAtDate: end.toISOString(), timezone: 'Asia/Kolkata', latitude: 10.025, longitude: 76.309, joinType: 'open', visibility: 'public' }
    const invalid = await request('/api/scenes', { method: 'POST', cookie: host, body: { ...sceneBody, endsAtDate: new Date(start.getTime() - 1000).toISOString() } })
    assert.equal(invalid.status, 400)
    const created = await request('/api/scenes', { method: 'POST', cookie: host, body: sceneBody })
    assert.equal(created.status, 201, JSON.stringify(created.data))
    const id = created.data._id
    const discovered = await request('/api/scenes?city=Kochi')
    assert.ok(discovered.data.some((scene) => scene._id === id))
    assert.deepEqual(discovered.data.find((scene) => scene._id === id).members, [])
    assert.equal((await request('/api/scenes?city=Kochi&category=Concerts')).data.length, 0)
    assert.equal((await request('/api/scenes?city=Kochi&query=Public%20cafe')).data[0]._id, id)
    assert.equal((await request('/api/scenes?city=Kochi&price=free')).data[0]._id, id)
    assert.equal((await request('/api/scenes?city=Kochi&maxPrice=-1')).status, 400)
    assert.equal((await request('/api/scenes?city=Kochi&maxPrice=oops')).status, 400)
    assert.equal((await request('/api/scenes?city=Kochi&maxPrice=0')).data[0]._id, id)
    assert.ok(!(await request('/api/scenes?city=Kochi&locationType=online')).data.some((scene) => scene._id === id))
    assert.equal((await request('/api/scenes?saved=1')).status, 401)
    assert.equal((await request('/api/scenes?forYou=1')).status, 401)
    assert.equal((await request(`/api/scenes/${id}/save`, { method: 'PUT' })).status, 401)
    const saved = await request(`/api/scenes/${id}/save`, { method: 'PUT', cookie: guest })
    assert.equal(saved.status, 200)
    assert.deepEqual(saved.data.savedSceneIds, [id])
    assert.deepEqual((await request(`/api/scenes/${id}/save`, { method: 'PUT', cookie: guest })).data.savedSceneIds, [id])
    assert.ok((await request('/api/scenes?saved=1', { cookie: guest })).data.some((scene) => scene._id === id))
    assert.deepEqual((await request('/api/scenes?saved=1', { cookie: other })).data, [])
    assert.deepEqual((await request('/api/auth/me', { cookie: guest })).data.user.savedSceneIds, [id])
    assert.equal((await request(`/api/scenes/${id}/pass`)).status, 401)
    assert.equal((await request(`/api/scenes/${id}/pass`, { cookie: guest })).status, 403)
    const guestProfile = await request('/api/users/me', { method: 'PATCH', cookie: guest, body: { displayName: 'Test Guest', city: 'Kochi', interests: ['Comedy'] } })
    assert.equal(guestProfile.status, 200)
    const comedy = await request('/api/scenes', { method: 'POST', cookie: host, body: { ...sceneBody, title: 'Comedy Night', category: 'Comedy' } })
    assert.equal(comedy.status, 201)
    const recommended = await request('/api/scenes?city=Kochi&forYou=1', { cookie: guest })
    assert.ok(recommended.data.some((scene) => scene._id === comedy.data._id))
    assert.ok(!recommended.data.some((scene) => scene._id === id))
    assert.equal((await request(`/api/scenes/${comedy.data._id}`, { method: 'PATCH', cookie: host, body: { ...sceneBody, title: 'Comedy Night', category: 'Wellness' } })).status, 200)
    const nearby = await request('/api/scenes/nearby?latitude=10.025&longitude=76.309&km=5')
    assert.equal(nearby.status, 200, JSON.stringify(nearby.data))
    assert.ok(nearby.data.some((scene) => scene._id === id))
    const forbiddenEdit = await request(`/api/scenes/${id}`, { method: 'PATCH', cookie: guest, body: sceneBody })
    assert.equal(forbiddenEdit.status, 403)
    const deniedChat = await request(`/api/scenes/${id}/messages`, { cookie: guest })
    assert.equal(deniedChat.status, 403)
    const [a, b] = await Promise.all([guest, other].map((cookie) => request(`/api/scenes/${id}/join`, { method: 'POST', cookie })))
    assert.deepEqual([a.status, b.status].sort(), [200, 409])
    const winner = a.status === 200 ? guest : other
    const repeat = await request(`/api/scenes/${id}/join`, { method: 'POST', cookie: winner })
    assert.equal(repeat.status, 200)
    assert.equal(repeat.data.scene.joined, 2)
    const pass = await request(`/api/scenes/${id}/pass`, { cookie: winner })
    assert.equal(pass.status, 200)
    assert.equal(pass.data.status, 'CONFIRMED')
    assert.equal(pass.data.quantity, 1)
    assert.match(pass.data.reference, /^SCN-[A-F0-9]{12}$/)
    assert.equal((await request(`/api/scenes/${id}/pass`, { cookie: winner })).data.reference, pass.data.reference)
    assert.equal((await request(`/api/scenes/${id}/pass`, { cookie: winner === guest ? other : guest })).status, 403)
    const allowedChat = await request(`/api/scenes/${id}/messages`, { cookie: winner })
    assert.equal(allowedChat.status, 200)
    const message = await request(`/api/scenes/${id}/messages`, { method: 'POST', cookie: winner, body: { text: 'See you there!' } })
    assert.equal(message.status, 201)
    assert.equal((await request(`/api/scenes/${id}/messages`, { cookie: winner })).data.length, 1)
    const left = await request(`/api/scenes/${id}/leave`, { method: 'POST', cookie: winner })
    assert.equal(left.status, 200)
    assert.equal(left.data.joined, 1)
    assert.equal((await request(`/api/scenes/${id}/messages`, { cookie: winner })).status, 403)
    assert.equal((await request(`/api/scenes/${id}/pass`, { cookie: winner })).status, 403)
    assert.deepEqual((await request(`/api/scenes/${id}/save`, { method: 'DELETE', cookie: guest })).data.savedSceneIds, [])
    assert.deepEqual((await request(`/api/scenes/${id}/save`, { method: 'DELETE', cookie: guest })).data.savedSceneIds, [])
    const privateScene = await request('/api/scenes', { method: 'POST', cookie: host, body: { ...sceneBody, title: 'Private Scene', visibility: 'private' } })
    assert.equal(privateScene.status, 201)
    const listed = await request('/api/scenes?city=Kochi')
    assert.ok(!listed.data.some((scene) => scene._id === privateScene.data._id))
    const hidden = await request(`/api/scenes/${privateScene.data._id}`, { cookie: guest })
    assert.equal(hidden.status, 404)
    assert.equal((await request(`/api/scenes/${privateScene.data._id}/save`, { method: 'PUT', cookie: guest })).status, 404)
    await request(`/api/scenes/${comedy.data._id}/save`, { method: 'PUT', cookie: guest })
    await request(`/api/scenes/${comedy.data._id}`, { method: 'PATCH', cookie: host, body: { visibility: 'private' } })
    assert.ok(!(await request('/api/scenes?saved=1', { cookie: guest })).data.some((scene) => scene._id === comedy.data._id))
    const ownerView = await request(`/api/scenes/${privateScene.data._id}`, { cookie: host })
    assert.equal(ownerView.status, 200)
    assert.deepEqual((await request('/api/scenes?mine=1&query=Private', { cookie: guest })).data, [])
    const draft = await request('/api/scenes', { method: 'POST', cookie: host, body: { title: 'Draft Scene', category: 'Concerts', capacity: 10, publication: 'draft' } })
    assert.equal(draft.status, 201)
    assert.equal(draft.data.publication, 'draft')
    assert.equal((await request(`/api/scenes/${draft.data._id}/save`, { method: 'PUT', cookie: host })).status, 404)
    assert.ok(!(await request('/api/scenes?city=Kochi')).data.some((scene) => scene._id === draft.data._id))
    const publish = await request(`/api/scenes/${draft.data._id}`, { method: 'PATCH', cookie: host, body: { ...sceneBody, title: 'Published Draft', publication: 'published' } })
    assert.equal(publish.status, 200, JSON.stringify(publish.data))
    assert.ok((await request('/api/scenes?city=Kochi')).data.some((scene) => scene._id === draft.data._id))
    const currentScene = await request('/api/scenes', { method: 'POST', cookie: host, body: { ...sceneBody, title: 'Current Scene', startsAt: new Date(Date.now() - 600000).toISOString(), endsAtDate: new Date(Date.now() + 3600000).toISOString() } })
    assert.equal(currentScene.status, 201)
    assert.equal(currentScene.data.eventStatus, 'IN PROGRESS')
    assert.equal((await request(`/api/scenes/${currentScene.data._id}/live`, { method: 'POST', cookie: guest })).status, 403)
    const confirmed = await request(`/api/scenes/${currentScene.data._id}/live`, { method: 'POST', cookie: host })
    assert.equal(confirmed.status, 200)
    assert.equal(confirmed.data.eventStatus, 'LIVE NOW')
    const approvalScene = await request('/api/scenes', { method: 'POST', cookie: host, body: { ...sceneBody, title: 'Approval Scene', joinType: 'approval' } })
    assert.equal(approvalScene.status, 201)
    const approvalId = approvalScene.data._id
    const pending = await request(`/api/scenes/${approvalId}/join`, { method: 'POST', cookie: guest })
    assert.equal(pending.status, 202)
    assert.equal(pending.data.scene.requestStatus, 'PENDING')
    assert.equal((await request(`/api/scenes/${approvalId}/pass`, { cookie: guest })).status, 403)
    assert.ok((await request('/api/scenes?requested=1', { cookie: guest })).data.some((scene) => scene._id === approvalId))
    const requestList = await request(`/api/scenes/${approvalId}/requests`, { cookie: host })
    assert.equal(requestList.status, 200)
    assert.equal(requestList.data.length, 1)
    const approved = await request(`/api/scenes/${approvalId}/requests/${requestList.data[0].id}`, { method: 'POST', cookie: host, body: { decision: 'APPROVED' } })
    assert.equal(approved.status, 200, JSON.stringify(approved.data))
    assert.equal(approved.data.scene.joined, 2)
    assert.equal((await request(`/api/scenes/${approvalId}/pass`, { cookie: guest })).status, 200)
    assert.ok(!(await request('/api/scenes?requested=1', { cookie: guest })).data.some((scene) => scene._id === approvalId))
    assert.equal((await request(`/api/scenes/${approvalId}/messages`, { cookie: guest })).status, 200)
    const cancelled = await request(`/api/scenes/${approvalId}/cancel`, { method: 'POST', cookie: host })
    assert.equal(cancelled.status, 200)
    assert.equal((await request(`/api/scenes/${approvalId}/pass`, { cookie: guest })).data.status, 'CANCELLED')
    assert.ok(!(await request('/api/scenes?city=Kochi')).data.some((scene) => scene._id === approvalId))
    const forgot = await request('/api/auth/password/forgot', { method: 'POST', body: { email: 'testhost@example.test' } })
    assert.equal(forgot.status, 200)
    const resetToken = mailbox.get('testhost@example.test').html.match(/\?reset=([A-Za-z0-9_-]+)/)?.[1]
    assert.ok(resetToken)
    const reset = await request('/api/auth/password/reset', { method: 'POST', body: { token: resetToken, password: 'a-new-correct-password' } })
    assert.equal(reset.status, 200)
    assert.equal((await request('/api/auth/me', { cookie: host })).data.user, null)
    const newLogin = await request('/api/auth/login', { method: 'POST', body: { email: 'testhost@example.test', password: 'a-new-correct-password' } })
    assert.equal(newLogin.status, 200)
    const logout = await request('/api/auth/logout', { method: 'POST', cookie: newLogin.cookie })
    assert.equal(logout.status, 204)
    assert.equal((await request('/api/auth/me', { cookie: newLogin.cookie })).data.user, null)
  } finally {
    if (server.exitCode === null) { server.kill('SIGTERM'); await new Promise((resolve) => server.once('exit', resolve)) }
    await new Promise((resolve) => emailServer.close(resolve))
    const connection = await mongoose.createConnection(mongoUri).asPromise()
    await connection.dropDatabase()
    await connection.close()
    await rm(avatarDirectory, { recursive: true, force: true })
  }
})
